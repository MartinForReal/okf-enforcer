import assert from "node:assert/strict";
import { test } from "node:test";
import { readFile, writeFile, access, rm } from "node:fs/promises";
import path from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";

test("preparing a marked fixture again resets only the generated missing-index control", async () => {
  const prepare = (root?: string) => {
    const result = spawnSync(process.execPath, ["tests/e2e/prepare.mjs", ...(root ? [root] : [])], { encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr); return JSON.parse(result.stdout);
  };
  const fixture = prepare(); const root = path.resolve(fixture.fixtureRoot);
  // This invocation created this exact temp fixture; never clean another path.
  assert.equal(path.dirname(root), path.resolve(tmpdir())); assert.match(path.basename(root), /^okf-enforcer-e2e-/);
  try {
    const generated = path.join(fixture.vault, "gap", "index.md");
    const unrelated = path.join(fixture.vault, "unrelated.txt");
    await writeFile(generated, "# Generated by the intentional index control\n");
    await writeFile(unrelated, "Preserve this artifact\n");
    prepare(root);
    await assert.rejects(access(generated), { code: "ENOENT" });
    assert.equal(await readFile(unrelated, "utf8"), "Preserve this artifact\n");
  } finally { await rm(root, { recursive: true, force: true }); }
});
